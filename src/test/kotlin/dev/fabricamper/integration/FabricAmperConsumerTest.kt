/**
 * Opt-in TestKit acceptance: each fixture contains settings.gradle.kts and
 * mod.yaml (plus consumer sources/resources where relevant), never build.gradle.
 *
 * These tests apply actual Fabric Loom and may resolve a Minecraft distribution.
 * They require Gradle/JDK 25, a network-enabled isolated test environment and
 * `FABRIC_AMPER_TESTKIT_FULL=true` in the Gradle launch environment. An omitted
 * variable yields SKIPPED, not PASS. Gradle JVM -D properties are not silently
 * assumed to propagate into the forked test JVM.
 * GradleRunner uses the project's currently running Gradle version.
 */
@EnabledIfEnvironmentVariable(named = "FABRIC_AMPER_TESTKIT_FULL", matches = "true")
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class FabricAmperConsumerTest {
    @TempDir lateinit var suiteRoot: Path
    private val fixture get() = TestKitFixture(suiteRoot)

    @Test
    fun `G1 G2 G14 settings-only consumer applies project Loom and exposes all tasks`() {
        val f = fixture
        val root = f.project("g1-g2-g14")
        f.assertNoConsumerBuildScript(root)
        val help = f.run(root, "help")
        assertTrue(help.output.contains("BUILD SUCCESSFUL"), help.output)
        val tasks = f.run(root, "tasks", "--all").output
        for (name in listOf("compileJava", "processResources", "generateFabricModJson", "jar", "runClient", "runServer")) {
            assertTrue(Regex("(?m)^${Regex.escape(name)}\\b").containsMatchIn(tasks), "Missing $name:\n$tasks")
        }
        assertTrue(root.resolve(".gradle/fabric-amper/loom").exists(), "Loom metadata mirror not created")
        assertFalse(root.resolve("src/main/resources/fabric.mod.json").exists())
        f.assertNoConsumerBuildScript(root)
    }

    @Test
    fun `G3 G21 generated bytes match mirror and final jar has exactly one root metadata`() {
        val f = fixture
        val root = f.project("g3-g21")
        writeJavaEntrypoint(f, root)
        f.run(root, "generateFabricModJson")
        val generated = f.generatedJson(root).readBytes()
        val mirror = f.mirrorJson(root).single().readBytes()
        assertArrayEquals(generated, mirror)
        assertTrue(generated.last() == '\n'.code.toByte(), "Expected one terminal newline")
        assertFalse(generated.dropLast(1).last() == '\n'.code.toByte(), "Expected exactly one terminal newline")
        val json = JsonParser.parseString(String(generated, StandardCharsets.UTF_8)).asJsonObject
        assertEquals("testkit_mod", json.get("id").asString)
        assertEquals("1.0.0+26.3", json.get("version").asString)
        f.run(root, "build")
        val jar = f.jars(root).single()
        assertEquals("testkit-mod-1.0.0+26.3.jar", jar.name)
        val (count, bytes) = f.jarRootJson(jar)
        assertEquals(1, count, "Jar root must contain one fabric.mod.json")
        assertArrayEquals(generated, bytes)
        ZipFile(jar.toFile()).use { zip ->
            assertTrue(zip.getEntry("org/example/TestkitEntry.class") != null, "No compiled consumer class")
        }
        f.run(root, "jar")
        assertEquals(1, f.jarRootJson(jar).first)
        f.assertNoConsumerBuildScript(root)
    }

    @Test
    fun `G4 changing mod id version and archive name regenerates project output`() {
        val f = fixture
        val root = f.project("g4")
        f.run(root, "build")
        val first = JsonParser.parseString(f.generatedJson(root).readText()).asJsonObject
        assertEquals("testkit_mod", first.get("id").asString)
        val updated = f.yaml(root)
            .replace("id: testkit_mod", "id: revised_mod")
            .replace("version: \"1.0.0+26.3\"", "version: \"1.0.1+26.3\"")
            .replace("archivesName: testkit-mod", "archivesName: revised-artifact")
        f.write(root, "mod.yaml", updated)
        f.run(root, "build")
        val second = JsonParser.parseString(f.generatedJson(root).readText()).asJsonObject
        assertEquals("revised_mod", second.get("id").asString)
        assertEquals("1.0.1+26.3", second.get("version").asString)
        val jar = f.jars(root).single { it.name == "revised-artifact-1.0.1+26.3.jar" }
        assertEquals(1, f.jarRootJson(jar).first)
        assertTrue(f.mirrorJson(root).any { it.readText() == f.generatedJson(root).readText() })
    }

    @Test
    fun `G5 configuration cache reuses then invalidates and reuses on YAML edits`() {
        val f = fixture
        val root = f.project("g5")
        // Cold Loom bootstrap can create its own version-manifest cache files
        // during the first configuration. Prime those external files before
        // measuring Amper's four strict configuration-cache HIT/MISS assertions.
        f.run(root, "help")
        val first = f.run(root, "build", "--configuration-cache")
        assertTrue(first.output.contains("BUILD SUCCESSFUL"), first.output)
        val second = f.run(root, "build", "--configuration-cache")
        assertTrue(second.output.contains("Reusing configuration cache"), second.output)
        val revised = f.yaml(root)
            .replace("version: \"1.0.0+26.3\"", "version: \"1.2.3+26.3\"") +
            "\ndependencies:\n  - \"com.google.code.gson:gson:2.14.0\": compile-only\n"
        f.write(root, "mod.yaml", revised)
        val third = f.run(root, "build", "--configuration-cache")
        assertFalse(third.output.contains("Reusing configuration cache"), third.output)
        assertEquals("1.2.3+26.3", JsonParser.parseString(f.generatedJson(root).readText())
            .asJsonObject.get("version").asString)
        val fourth = f.run(root, "build", "--configuration-cache")
        assertTrue(fourth.output.contains("Reusing configuration cache"), fourth.output)
    }

    @Test
    fun `G7 Java-only and Kotlin enabled builds apply language plugin conditionally`() {
        val f = fixture
        val root = f.project("g7")
        writeJavaEntrypoint(f, root)
        val javaTasks = f.run(root, "tasks", "--all").output
        assertFalse(Regex("(?m)^compileKotlin\\b").containsMatchIn(javaTasks), javaTasks)
        f.run(root, "build")
        val originalJar = f.jars(root).single()
        assertTrue(ZipFile(originalJar.toFile()).use { it.getEntry("org/example/TestkitEntry.class") != null })
        val enabled = f.yaml(root)
            .replace("enabled: false", "enabled: true\n    pluginVersion: \"2.4.21\"\n    languageVersion: \"2.4\"\n    fabricLanguageKotlin: \"1.14.2+kotlin.2.4.21\"")
            .replace("- org.example.TestkitEntry", "- adapter: kotlin\n        value: org.example.KotlinEntry")
        f.write(root, "mod.yaml", enabled)
        f.write(root, "src/main/kotlin/org/example/KotlinEntry.kt", """
            package org.example
            class KotlinEntry : net.fabricmc.api.ModInitializer {
                override fun onInitialize() {}
            }
        """.trimIndent() + "\n")
        val kotlinTasks = f.run(root, "tasks", "--all").output
        assertTrue(Regex("(?m)^compileKotlin\\b").containsMatchIn(kotlinTasks), kotlinTasks)
        f.run(root, "build")
        val json = JsonParser.parseString(f.generatedJson(root).readText()).asJsonObject
        assertEquals("kotlin", json.getAsJsonObject("entrypoints").getAsJsonArray("main")
            .first().asJsonObject.get("adapter").asString)
        val jar = f.jars(root).single()
        ZipFile(jar.toFile()).use { zip ->
            assertTrue(zip.getEntry("org/example/KotlinEntry.class") != null, "Compiled Kotlin class missing")
        }
        f.write(root, "mod.yaml", f.resource("minimal-mod.yaml"))
        val disabled = f.run(root, "tasks", "--all").output
        assertFalse(Regex("(?m)^compileKotlin\\b").containsMatchIn(disabled), disabled)
        f.assertNoConsumerBuildScript(root)
    }

    @Test
    fun `G17a Loom receives configuration-time mirror before generator task runs`() {
        val f = fixture
        val yaml = f.resource("minimal-mod.yaml").replace(
            "  environment: \"*\"",
            "  environment: \"*\"\n  custom:\n    testkit:\n      injectedMetadataProbe: true",
        )
        val root = f.project("g17a", yaml)
        assertFalse(root.resolve("src/main/resources/fabric.mod.json").exists())
        assertFalse(f.generatedJson(root).exists())
        // The init script observes the extension value without adding a build.gradle
        // to the consumer. It is intentionally not used by other fixtures.
        f.write(root, "loom-probe.gradle", """
            gradle.projectsEvaluated {
                def loom = rootProject.extensions.getByName('loom')
                println('FABRIC_AMPER_LOOM_METADATA=' + loom.fabricModJsonPath.get().asFile.absolutePath)
            }
        """.trimIndent() + "\n")
        val result = f.run(root, "help", "--init-script", root.resolve("loom-probe.gradle").toString())
        val mirror = f.mirrorJson(root).single()
        assertTrue(result.output.contains("FABRIC_AMPER_LOOM_METADATA="), result.output)
        assertTrue(result.output.contains(mirror.toFile().absolutePath), result.output)
        assertTrue(mirror.readText().contains("injectedMetadataProbe"))
        assertFalse(f.generatedJson(root).exists(), "Task output was generated during configuration")
        f.assertNoConsumerBuildScript(root)
    }

    @Test
    fun `G20 missing or corrupted content-addressed mirror is restored with configuration cache`() {
        val f = fixture
        val root = f.project("g20")
        f.run(root, "generateFabricModJson", "--configuration-cache")
        val generated = f.generatedJson(root).readBytes()
        val mirror = f.mirrorJson(root).single()
        Files.delete(mirror)
        f.run(root, "generateFabricModJson", "--configuration-cache")
        assertArrayEquals(generated, mirror.readBytes(), "Deleted mirror was not restored")
        Files.writeString(mirror, "{\"corrupt\":true}\n", StandardCharsets.UTF_8)
        f.run(root, "generateFabricModJson", "--configuration-cache")
        assertArrayEquals(generated, mirror.readBytes(), "Corrupted mirror was not repaired")
        f.run(root, "clean")
        f.run(root, "help")
        assertTrue(f.mirrorJson(root).any { it.readBytes().contentEquals(generated) })
    }

    @Test
    fun `G24 referenced mixin icon and classTweaker survive snapshot and jar unchanged`() {
        val f = fixture
        val yaml = f.resource("minimal-mod.yaml").replace(
            "  entrypoints:",
            "  mixins:\n    - example.mixins.json\n  accessWidener: example.classtweaker\n" +
                "  icon: assets/testkit_mod/icon.png\n  entrypoints:",
        )
        val root = f.project("g24", yaml)
        val mixin = f.resource("example.mixins.json")
        val tweaker = "classTweaker v1 official\n"
        f.write(root, "src/main/resources/example.mixins.json", mixin)
        f.write(root, "src/main/resources/example.classtweaker", tweaker)
        val icon = TestKitFixture.onePixelPng
        assertNotNull(ImageIO.read(ByteArrayInputStream(icon)), "G24 must use a decodable PNG icon")
        f.writeBytes(root, "src/main/resources/assets/testkit_mod/icon.png", icon)
        f.run(root, "help")
        val before = f.mirrorJson(root).single().parent
        assertEquals(mixin, before.resolve("example.mixins.json").readText())
        assertEquals(tweaker, before.resolve("example.classtweaker").readText())
        assertArrayEquals(TestKitFixture.onePixelPng, before.resolve("assets/testkit_mod/icon.png").readBytes())
        f.run(root, "build")
        val jar = f.jars(root).single()
        ZipFile(jar.toFile()).use { zip ->
            for (name in listOf("example.mixins.json", "example.classtweaker", "assets/testkit_mod/icon.png")) {
                assertEquals(1, zip.entries().asSequence().count { it.name == name }, "Duplicate or missing $name")
            }
        }
        assertEquals(1, f.jarRootJson(jar).first)
        f.write(root, "src/main/resources/example.mixins.json", mixin.trimEnd() + "\n\n")
        f.run(root, "help")
        val after = f.mirrorJson(root).first { it.parent != before }.parent
        assertEquals(mixin.trimEnd() + "\n\n", after.resolve("example.mixins.json").readText())
    }

    private fun writeJavaEntrypoint(f: TestKitFixture, root: Path) {
        f.write(root, "src/main/java/org/example/TestkitEntry.java", """
            package org.example;
            public final class TestkitEntry implements net.fabricmc.api.ModInitializer {
                @Override public void onInitialize() {}
            }
        """.trimIndent() + "\n")
    }
}
