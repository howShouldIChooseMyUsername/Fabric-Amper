/**
 * Structural contract for Prime-owned, standalone Draft-07 JSON Schema.
 * Uses existing Gson and the real YAML parser; it is NOT a JSON Schema evaluator.
 * The root schema must not be rewritten or generated by these tests.
 */
class FabricAmperSchemaContractUnitTest {
    @TempDir lateinit var project: Path

    private fun schema(): JsonObject {
        val file = Path.of(System.getProperty("user.dir")).resolve("fabric-amper.schema.json")
        assertTrue(Files.isRegularFile(file), "Standalone root schema is missing: $file")
        return JsonParser.parseString(Files.readString(file, StandardCharsets.UTF_8)).asJsonObject
    }

    private fun JsonObject.stringSet(name: String): Set<String> =
        getAsJsonArray(name).map { it.asString }.toSet()

    @Test
    fun `standalone root JSON schema declares Draft 07 and exact strict YAML root fields`() {
        val root = schema()
        assertTrue(root.get("\$schema").asString.matches(
            Regex("https?://json-schema\\.org/draft-07/schema#?")), "SchemaStore-compatible Draft-07 required")
        assertEquals("object", root.get("type").asString)
        assertFalse(root.get("additionalProperties").asBoolean, "Unrecognized YAML roots must not be accepted")
        assertEquals(setOf("product", "mod", "minecraft"), root.stringSet("required"))
        assertEquals(setOf(
            "schema", "product", "mod", "minecraft", "settings", "repositories",
            "dependencies", "test-dependencies", "publishing", "publish", "architectury",
            "fabric", "neoforge",
        ), root.getAsJsonObject("properties").keySet(), "Schema root must mirror strict decoder keys")
        val version = root.getAsJsonObject("properties").getAsJsonObject("schema")
        val supported = version.getAsJsonArray("oneOf").map { it.asJsonObject }
        assertEquals(2, supported.size)
        assertTrue(supported.any { it.get("type").asString == "integer" && it.get("const").asInt == 1 })
        assertTrue(supported.any { it.get("type").asString == "string" && it.get("const").asString == "1.1" })
        assertEquals("1.1", version.get("default").asString,
            "An omitted schema must select the loader-namespaced 1.1 contract")
    }

    @Test
    fun `all user product names appear once and alias retains a shared API profile`() {
        val root = schema()
        val declared = root.getAsJsonObject("properties").getAsJsonObject("product")
        val productVariants = declared.getAsJsonArray("oneOf").map { it.asJsonObject }
        val stringVariant = productVariants.single { it.get("type").asString == "string" }
        val arrayVariant = productVariants.single { it.get("type").asString == "array" }
        val names = setOf("fabric/mod", "fabric/api", "fabric/library", "neoforge/mod", "neoforge/api")
        assertEquals(names, stringVariant.stringSet("enum"))
        assertEquals(names, arrayVariant.getAsJsonObject("items").stringSet("enum"))
        assertTrue(arrayVariant.get("uniqueItems").asBoolean)
        // Root conditions are unordered: newer Minecraft/profile guards can be
        // inserted before this API/library rule without changing its meaning.
        val branch = root.getAsJsonArray("allOf").map { it.asJsonObject }.singleOrNull { condition ->
            condition.getAsJsonObject("if")?.getAsJsonObject("properties")
                ?.getAsJsonObject("product")?.getAsJsonArray("enum")
                ?.map { it.asString }?.toSet() == setOf("fabric/api", "fabric/library")
        }
        assertNotNull(branch, "Expected exactly one API/library product condition in allOf")
        val apiBranch = requireNotNull(branch)
        assertEquals(setOf("fabric/api", "fabric/library"),
            apiBranch.getAsJsonObject("if").getAsJsonObject("properties")
                .getAsJsonObject("product").stringSet("enum"))
        val thenMod = apiBranch.getAsJsonObject("then").getAsJsonObject("properties")
            .getAsJsonObject("mod")
        assertTrue("group" in thenMod.stringSet("required"), "API Maven group is mandatory")
        val legacyModGuard = apiBranch.getAsJsonObject("else")
        assertEquals("1.1", legacyModGuard.getAsJsonObject("if").getAsJsonObject("properties")
            .getAsJsonObject("schema").getAsJsonObject("not").get("const").asString)
        assertTrue("publishing" in legacyModGuard.getAsJsonObject("then").getAsJsonObject("not").stringSet("required"),
            "legacy fabric/mod must reject publishing even when empty")
    }

    @Test
    fun `all references are internal and structural definitions preserve strict decoder contracts`() {
        val root = schema()
        val definitions = root.getAsJsonObject("definitions")
        for (name in listOf(
            "mod", "minecraft", "settings", "architectury", "entrypoint", "versionMap", "dependency",
            "dependencyObject", "testDependency", "repository", "publishing", "scope",
            "publish", "publishCommon", "publishCommonDependency", "publishMaven", "publishModrinth", "publishCurseForge",
            "publishModrinthDependency", "publishCurseForgeRelation", "envName", "releaseType",
        )) {
            assertTrue(definitions.has(name), "Missing local definition: $name")
        }
        fun traverse(element: JsonElement) {
            when {
                element.isJsonObject -> {
                    val obj = element.asJsonObject
                    if (obj.has("\$ref")) {
                        val ref = obj.get("\$ref").asString
                        assertTrue(ref.startsWith("#/definitions/"), "No external or dangling references: $ref")
                        var current: JsonElement = root
                        for (token in ref.removePrefix("#/").split('/')) {
                            val key = token.replace("~1", "/").replace("~0", "~")
                            current = when {
                                current.isJsonObject -> current.asJsonObject.get(key)
                                current.isJsonArray -> key.toIntOrNull()?.let { index ->
                                    current.asJsonArray.takeIf { index in 0 until it.size() }?.get(index)
                                }
                                else -> null
                            } ?: throw AssertionError("Missing reference: $ref")
                        }
                    }
                    obj.entrySet().forEach { (_, value) -> traverse(value) }
                }
                element.isJsonArray -> element.asJsonArray.forEach(::traverse)
            }
        }
        traverse(root)
        for (name in listOf("mod", "minecraft", "settings", "publishing", "dependencyObject")) {
            assertFalse(definitions.getAsJsonObject(name).get("additionalProperties").asBoolean,
                "Known $name keys should stay strict")
        }
        assertTrue(definitions.getAsJsonObject("mod").getAsJsonObject("properties")
            .getAsJsonObject("custom").get("additionalProperties").asBoolean,
            "Only deliberate Loader custom metadata must remain extensible")
    }

    @Test
    fun `dependency entry advertises typed keys directly for IntelliJ YAML array completion`() {
        val root = schema()
        val definitions = root.getAsJsonObject("definitions")
        val dependencies = root.getAsJsonObject("properties").getAsJsonObject("dependencies")
        assertEquals("#/definitions/dependency", dependencies.getAsJsonObject("items").get("\$ref").asString)

        val item = definitions.getAsJsonObject("dependency")
        assertEquals(listOf("object", "string"), item.getAsJsonArray("type").map { it.asString })
        val keys = item.getAsJsonObject("properties")
        assertEquals(setOf("maven", "modrinth", "kind", "scope", "target", "exported", "include"),
            keys.keySet(), "Autocomplete must expose the supported keys at the array item, not just under oneOf")
        assertEquals(definitions.getAsJsonObject("dependencyObject").getAsJsonObject("properties"), keys,
            "IDE completion properties must never drift from strict object validation")
        assertEquals(setOf("mod", "library"), keys.getAsJsonObject("kind").stringSet("enum"))
        assertEquals("boolean", keys.getAsJsonObject("include").get("type").asString)
        assertEquals(3, item.getAsJsonArray("oneOf").size(),
            "String and map shorthand must remain supported alongside the typed object form")

        val yaml = YamlFixtures.valid + """
            repositories:
              - fabric
              - mavenCentral
              - maven: "https://maven.nucleoid.xyz/"
            dependencies:
              - maven: "xyz.nucleoid:fantasy:0.8.4+26.3"
                kind: mod
                scope: all
                target: main
                include: true
        """.trimIndent() + "\n"
        val parsed = ModYamlLoader.load(YamlFixtures.write(project, yaml))
        assertEquals("xyz.nucleoid:fantasy:0.8.4+26.3", parsed.dependencies.single().coordinate)
        assertEquals("mod", parsed.dependencies.single().kind)
        assertTrue(parsed.dependencies.single().include)
    }

    @Test
    fun `API publishing definition has HTTPS without queries or embedded secrets and env names only`() {
        val publishing = schema().getAsJsonObject("definitions").getAsJsonObject("publishing")
        val repository = publishing.getAsJsonObject("properties").getAsJsonObject("repository")
        assertFalse(repository.get("additionalProperties").asBoolean)
        assertEquals(setOf("url"), repository.stringSet("required"))
        assertEquals(setOf("url", "usernameEnv", "passwordEnv"),
            repository.getAsJsonObject("properties").keySet())
        val props = repository.getAsJsonObject("properties")
        val urlPattern = Regex(props.getAsJsonObject("url").get("pattern").asString)
        for (url in listOf("https://maven.example.org/releases", "HTTPS://maven.example.org/releases")) {
            assertTrue(urlPattern.matches(url), "Valid uppercase/lowercase HTTPS URI rejected: $url")
        }
        for (url in listOf(
            "http://maven.example.org/releases", "https://user:pass@maven.example.org/releases",
            "https://maven.example.org/releases?token=test-value", "https://maven.example.org/releases#fragment",
        )) {
            assertFalse(urlPattern.matches(url), "Unsafe publishing URL schema acceptance: $url")
        }
        for (field in listOf("usernameEnv", "passwordEnv")) {
            val envPattern = Regex(props.getAsJsonObject(field).get("pattern").asString)
            assertTrue(envPattern.matches("FABRIC_AMPER_MAVEN_PASSWORD"))
            assertFalse(envPattern.matches("secret with spaces"))
            assertFalse(envPattern.matches("1INVALID"))
        }
    }

    @Test
    fun `legacy publishing schema requires both credential env fields or neither`() {
        val repository = schema().getAsJsonObject("definitions")
            .getAsJsonObject("publishing")
            .getAsJsonObject("properties")
            .getAsJsonObject("repository")
        assertEquals(setOf("url"), repository.stringSet("required"),
            "Anonymous HTTPS Maven publishing must remain valid")
        val dependencyPairs = repository.getAsJsonArray("allOf").map { rule ->
            val obj = rule.asJsonObject
            obj.getAsJsonObject("if").stringSet("required") to
                obj.getAsJsonObject("then").stringSet("required")
        }.toSet()
        assertEquals(setOf(
            setOf("usernameEnv") to setOf("passwordEnv"),
            setOf("passwordEnv") to setOf("usernameEnv"),
        ), dependencyPairs, "Draft-07 conditional requirements must mirror strict YAML XOR validation")
    }

    @Test
    fun `new publish schema has strict platform destinations and authenticated Maven environment pair`() {
        val root = schema()
        assertEquals("#/definitions/publish", root.getAsJsonObject("properties")
            .getAsJsonObject("publish").get("\$ref").asString)
        val definitions = root.getAsJsonObject("definitions")
        val publish = definitions.getAsJsonObject("publish")
        assertFalse(publish.get("additionalProperties").asBoolean)
        assertEquals(setOf("common", "maven", "modrinth", "curseforge"),
            publish.getAsJsonObject("properties").keySet())
        assertEquals(1, publish.get("minProperties").asInt)
        val maven = definitions.getAsJsonObject("publishMaven")
        assertFalse(maven.get("additionalProperties").asBoolean)
        assertEquals(setOf("url"), maven.stringSet("required"))
        val names = maven.getAsJsonObject("properties").getAsJsonObject("credentialsFromEnv")
        assertEquals(2, names.get("minItems").asInt)
        assertEquals(2, names.get("maxItems").asInt)
        assertTrue(names.get("uniqueItems").asBoolean)
        assertEquals("#/definitions/envName", names.getAsJsonObject("items").get("\$ref").asString)
        for ((name, required) in listOf(
            "publishModrinth" to setOf("projectId", "tokenEnv"),
            "publishCurseForge" to setOf("projectId", "tokenEnv"),
        )) {
            val platform = definitions.getAsJsonObject(name)
            assertFalse(platform.get("additionalProperties").asBoolean)
            assertEquals(required, platform.stringSet("required"))
            assertTrue(platform.getAsJsonObject("properties").has("changelogFile"))
            assertTrue(platform.getAsJsonObject("properties").has("releaseType"))
        }
        assertEquals(setOf("release", "beta", "alpha"),
            definitions.getAsJsonObject("releaseType").stringSet("enum"))
        assertEquals(setOf("required", "optional", "incompatible", "embedded"),
            definitions.getAsJsonObject("publishModrinthDependency")
                .getAsJsonObject("properties").getAsJsonObject("type").stringSet("enum"))
        assertEquals(setOf("embeddedLibrary", "incompatible", "optionalDependency", "requiredDependency", "tool"),
            definitions.getAsJsonObject("publishCurseForgeRelation")
                .getAsJsonObject("properties").getAsJsonObject("type").stringSet("enum"))
    }

    @Test
    fun `top level example is accepted by the actual Fabric Amper strict YAML parser`() {
        val example = schema().getAsJsonArray("examples")[0].asJsonObject
        // JSON object notation is also a legal YAML 1.2 flow mapping.  This
        // exercises the actual parser/validator, not a handwritten fake DTO.
        val source = YamlFixtures.write(project, example.toString())
        val model = ModYamlLoader.load(source)
        assertEquals(example.get("product").asString, model.product)
        assertEquals(example.getAsJsonObject("mod").get("id").asString, model.mod.id)
        assertEquals(example.getAsJsonObject("mod").get("group").asString, model.mod.group)
        assertEquals(example.getAsJsonObject("minecraft").get("version").asString, model.minecraft.version)
        assertNotNull(model.publishing, "An explicit empty publishing mapping is not an omitted property")
        assertNull(model.publishing?.repository, "No remote repository is configured by the example")
    }

    @Test
    fun `all destinations in root schema publish example parse with the actual strict YAML loader`() {
        val example = schema().getAsJsonArray("examples")[1].asJsonObject
        val source = YamlFixtures.write(project, example.toString())
        val model = ModYamlLoader.load(source)
        assertEquals("fabric/mod", model.product)
        assertNull(model.publishing, "New platform publish must not secretly add legacy Maven publication")
        assertEquals("org.example", model.mod.group)
        assertEquals(listOf("GITHUB_ACTOR", "GITHUB_TOKEN"), model.publish?.maven?.credentialsFromEnv)
        assertEquals("AABBCCDD", model.publish?.modrinth?.projectId)
        assertEquals(123456, model.publish?.curseforge?.projectId)
        assertEquals(listOf("26.3", "Fabric", "Client", "Server"),
            model.publish?.curseforge?.gameVersionNames)
    }

    @Test
    fun schemaCommonExampleParsesWithExplicitV1AndConvertsRelations() {
        val example = schema().getAsJsonArray("examples")[2].asJsonObject
        assertEquals(1, example.get("schema").asInt, "Legacy example must opt in to schema 1")
        val model = ModYamlLoader.load(YamlFixtures.write(project, example.toString()))
        assertEquals(1, model.schema)
        assertEquals("beta", model.publish?.common?.releaseType)
        assertEquals("beta", model.publish?.modrinth?.releaseType)
        assertEquals("beta", model.publish?.curseforge?.releaseType)
        assertEquals(listOf("26.3"), model.publish?.modrinth?.gameVersions)
        assertEquals(listOf("26.3", "Fabric"), model.publish?.curseforge?.gameVersionNames)
        assertEquals("306612", model.publish?.curseforge?.relations?.first()?.projectId)
        assertEquals("requiredDependency", model.publish?.curseforge?.relations?.first()?.type)
    }

    @Test
    fun `schema product branch agrees with parser for API group and mod publishing isolation`() {
        val basic = YamlFixtures.valid
        assertEquals("fabric/mod", ModYamlLoader.load(YamlFixtures.write(project, basic)).product)

        val apiMissingGroup = basic.replace("product: fabric/mod", "product: fabric/api")
        assertEquals("mod.group", YamlFixtures.configError("FA003") {
            ModYamlLoader.load(YamlFixtures.write(project, apiMissingGroup))
        }.yamlPath)
        val modWithPublishing = basic + "publishing: {}\n"
        assertEquals("publishing", YamlFixtures.configError("FA003") {
            ModYamlLoader.load(YamlFixtures.write(project, modWithPublishing))
        }.yamlPath)
    }
